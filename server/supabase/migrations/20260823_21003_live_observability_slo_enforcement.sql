-- Powder 21.0.3 · Live Observability & SLO Enforcement
-- Server-derived SLO/SLI, multi-window burn-rate, error-budget guard and safe HALT.
begin;

create table if not exists public.live_slo_config_v21003(
  channel text primary key check(channel in ('production','staging')),
  build_id text not null default 'powder-21.0.3-live-observability-slo',
  manifest_hash text not null default '',
  artifact_sha256 text not null default '',
  enabled boolean not null default true,
  armed boolean not null default false,
  evidence_max_age_minutes integer not null default 15 check(evidence_max_age_minutes between 5 and 120),
  min_requests_60m integer not null default 500 check(min_requests_60m between 100 and 10000000),
  availability_target double precision not null default 0.995 check(availability_target between 0.90 and 0.99999),
  p95_target_ms integer not null default 1500 check(p95_target_ms between 100 and 30000),
  p99_target_ms integer not null default 2500 check(p99_target_ms between 100 and 60000),
  fast_burn_max double precision not null default 4.0 check(fast_burn_max between 1 and 100),
  slow_burn_max double precision not null default 2.0 check(slow_burn_max between 1 and 100),
  error_budget_remaining_min double precision not null default 0.25 check(error_budget_remaining_min between 0 and 1),
  state text not null default 'hold' check(state in ('healthy','hold','degraded')),
  last_reason text not null default '',
  armed_at timestamptz,
  updated_at timestamptz not null default now(),
  updated_by text not null default ''
);
insert into public.live_slo_config_v21003(channel) values('production'),('staging') on conflict(channel) do nothing;

