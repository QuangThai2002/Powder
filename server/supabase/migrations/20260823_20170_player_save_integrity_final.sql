create or replace function public.powder_player_save_snapshot_v20170()
returns trigger language plpgsql security definer set search_path=public as $$
declare s jsonb:=coalesce(new.integrity_summary,public.powder_save_integrity_summary_v20170(new.save_data));prev public.save_integrity_snapshots_v20170;
begin
 select * into prev from public.save_integrity_snapshots_v20170 where user_id=new.user_id order by revision desc limit 1;
 insert into public.save_integrity_snapshots_v20170(user_id,revision,save_version,schema_version,app_version,device_id,save_sha256,main_sha256,world_sha256,pow_ids_sha256,lessons_sha256,pow_count,lessons_count,equipment_copy_count,artifact_instance_count,critical_shape,summary,captured_at)
 values(new.user_id,new.revision,coalesce((s->>'saveVersion')::int,0),coalesce(new.schema_version,0),coalesce(new.app_version,''),coalesce(new.device_id,''),s->>'saveSha256',s->>'mainSha256',s->>'worldSha256',s->>'powIdsSha256',s->>'lessonsSha256',coalesce((s->>'powCount')::int,0),coalesce((s->>'lessonsCount')::int,0),coalesce((s->>'equipmentCopies')::bigint,0),coalesce((s->>'artifactInstances')::int,0),coalesce((s->>'criticalShape')::boolean,false),s,now())
 on conflict(user_id,revision) do update set save_sha256=excluded.save_sha256,main_sha256=excluded.main_sha256,world_sha256=excluded.world_sha256,pow_ids_sha256=excluded.pow_ids_sha256,lessons_sha256=excluded.lessons_sha256,pow_count=excluded.pow_count,lessons_count=excluded.lessons_count,equipment_copy_count=excluded.equipment_copy_count,artifact_instance_count=excluded.artifact_instance_count,critical_shape=excluded.critical_shape,summary=excluded.summary,captured_at=excluded.captured_at;
 if prev.user_id is not null and new.revision=prev.revision and prev.save_sha256<>coalesce(s->>'saveSha256','') then
  insert into public.save_integrity_incidents_v20170(user_id,revision,severity,code,details) values(new.user_id,new.revision,'high','SAVE20170_SAME_REVISION_HASH_DRIFT',jsonb_build_object('previous',prev.save_sha256,'current',s->>'saveSha256','device',new.device_id));
 end if;
 if prev.user_id is not null and prev.device_id<>coalesce(new.device_id,'') and new.revision<=prev.revision then
  insert into public.save_integrity_incidents_v20170(user_id,revision,severity,code,details) values(new.user_id,new.revision,'high','SAVE20170_STALE_DEVICE_COMMIT',jsonb_build_object('previousRevision',prev.revision,'previousDevice',prev.device_id,'device',new.device_id));
 end if;
 return new;
end$$;

