create or replace function public.powder_save_integrity_summary_v20170(p_save jsonb)
returns jsonb language plpgsql immutable as $$
declare
 main jsonb;world jsonb;owned jsonb;lessons jsonb;eq jsonb;arts jsonb;
 pow_count int:=0;lesson_count int:=0;eq_count bigint:=0;art_count int:=0;
 save_version int:=0;critical_shape boolean:=false;pow_ids text:='';lesson_ids text:='';
begin
 if jsonb_typeof(p_save)<>'object' then
  return jsonb_build_object('criticalShape',false,'error','SAVE_NOT_OBJECT','powCount',0,'lessonsCount',0,'equipmentCopies',0,'artifactInstances',0,'saveVersion',0);
 end if;
 main:=case when jsonb_typeof(p_save->'main')='object' then p_save->'main' else p_save end;
 world:=case when jsonb_typeof(p_save->'world')='object' then p_save->'world' else '{}'::jsonb end;
 owned:=case when jsonb_typeof(main->'owned')='object' then main->'owned' else '{}'::jsonb end;
 lessons:=case when jsonb_typeof(main->'lessonsDone')='array' then main->'lessonsDone' when jsonb_typeof(main->'lessonsDone')='object' then main->'lessonsDone' else '[]'::jsonb end;
 eq:=case when jsonb_typeof(world->'equipmentOwned')='object' then world->'equipmentOwned' else '{}'::jsonb end;
 arts:=case when jsonb_typeof(world->'artifactInstances')='object' then world->'artifactInstances' else '{}'::jsonb end;
 pow_count:=jsonb_object_length(owned);
 if jsonb_typeof(lessons)='array' then lesson_count:=jsonb_array_length(lessons); else lesson_count:=jsonb_object_length(lessons); end if;
 select coalesce(sum(case when value#>>'{}' ~ '^[0-9]+$' then (value#>>'{}')::bigint else 0 end),0) into eq_count from jsonb_each(eq);
 art_count:=jsonb_object_length(arts);
 save_version:=case when coalesce(main->>'saveVersion','')~'^[0-9]+$' then (main->>'saveVersion')::int else 0 end;
 select coalesce(string_agg(key,',' order by key),'') into pow_ids from jsonb_object_keys(owned) key;
 if jsonb_typeof(lessons)='array' then select coalesce(string_agg(value,',' order by value),'') into lesson_ids from jsonb_array_elements_text(lessons) value;
 else select coalesce(string_agg(key,',' order by key),'') into lesson_ids from jsonb_object_keys(lessons) key; end if;
 critical_shape:=jsonb_typeof(main)='object'
  and (not (main ? 'owned') or jsonb_typeof(main->'owned')='object')
  and (not (main ? 'learning') or jsonb_typeof(main->'learning')='object')
  and (jsonb_typeof(p_save->'world') is null or jsonb_typeof(p_save->'world')='object')
  and (not (world ? 'equipmentOwned') or jsonb_typeof(world->'equipmentOwned')='object')
  and (not (world ? 'artifactInstances') or jsonb_typeof(world->'artifactInstances')='object');
 return jsonb_build_object(
  'criticalShape',critical_shape,'saveVersion',save_version,'powCount',pow_count,'lessonsCount',lesson_count,
  'equipmentCopies',eq_count,'artifactInstances',art_count,
  'saveSha256',encode(digest(convert_to(p_save::text,'UTF8'),'sha256'),'hex'),
  'mainSha256',encode(digest(convert_to(main::text,'UTF8'),'sha256'),'hex'),
  'worldSha256',encode(digest(convert_to(world::text,'UTF8'),'sha256'),'hex'),
  'powIdsSha256',encode(digest(convert_to(pow_ids,'UTF8'),'sha256'),'hex'),
  'lessonsSha256',encode(digest(convert_to(lesson_ids,'UTF8'),'sha256'),'hex')
 );
end$$;

create or replace function public.powder_player_save_guard_v20170()
returns trigger language plpgsql security definer set search_path=public as $$
declare n jsonb;o jsonb:='{}'::jsonb;old_main jsonb;new_main jsonb;old_world jsonb;new_world jsonb;
begin
 if jsonb_typeof(new.save_data)<>'object' then raise exception 'SAVE20170_SAVE_NOT_OBJECT'; end if;
 n:=public.powder_save_integrity_summary_v20170(new.save_data);
 if coalesce((n->>'criticalShape')::boolean,false)=false then raise exception 'SAVE20170_CRITICAL_SHAPE_INVALID'; end if;
 if tg_op='UPDATE' then
  o:=public.powder_save_integrity_summary_v20170(old.save_data);
  if coalesce(new.revision,0)<coalesce(old.revision,0) then raise exception 'SAVE20170_REVISION_REGRESSION'; end if;
  if coalesce((n->>'saveVersion')::int,0)<coalesce((o->>'saveVersion')::int,0) then raise exception 'SAVE20170_SCHEMA_DOWNGRADE'; end if;
  if coalesce((o->>'powCount')::int,0)>0 and coalesce((n->>'powCount')::int,0)=0 then raise exception 'SAVE20170_POW_WIPE_BLOCKED'; end if;
  old_main:=case when jsonb_typeof(old.save_data->'main')='object' then old.save_data->'main' else old.save_data end;
  new_main:=case when jsonb_typeof(new.save_data->'main')='object' then new.save_data->'main' else new.save_data end;
  if jsonb_typeof(old_main->'learning')='object' and jsonb_object_length(old_main->'learning')>0 and jsonb_typeof(new_main->'learning')<>'object' then raise exception 'SAVE20170_LEARNING_BRANCH_LOSS'; end if;
  old_world:=case when jsonb_typeof(old.save_data->'world')='object' then old.save_data->'world' else '{}'::jsonb end;
  new_world:=case when jsonb_typeof(new.save_data->'world')='object' then new.save_data->'world' else '{}'::jsonb end;
  if coalesce((o->>'equipmentCopies')::bigint,0)>0 and (old_world ? 'equipmentOwned') and not(new_world ? 'equipmentOwned') then raise exception 'SAVE20170_EQUIPMENT_BRANCH_LOSS'; end if;
  if coalesce((o->>'artifactInstances')::int,0)>0 and (old_world ? 'artifactInstances') and not(new_world ? 'artifactInstances') then raise exception 'SAVE20170_ARTIFACT_BRANCH_LOSS'; end if;
 end if;
 new.integrity_version:='20.17.0';new.integrity_sha256:=n->>'saveSha256';new.integrity_checked_at:=now();new.integrity_summary:=n;
 return new;
end$$;

drop trigger if exists player_save_guard_v20170 on public.player_saves;
