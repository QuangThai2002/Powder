create or replace function public.powder_save_integrity_scan_v20170(p_actor text default '')
returns jsonb language plpgsql security definer set search_path=public as $$
declare total bigint:=0;malformed bigint:=0;missing bigint:=0;revbad bigint:=0;oc bigint:=0;oh bigint:=0;om bigint:=0;cfg public.save_integrity_config_v20170;ready boolean:=false;rid bigint;
begin
 select * into cfg from public.save_integrity_config_v20170 where id=1;
 select count(*) into total from public.player_saves;
 select count(*) into malformed from public.player_saves where jsonb_typeof(save_data)<>'object' or coalesce((integrity_summary->>'criticalShape')::boolean,false)=false or coalesce(integrity_sha256,'')!~'^[0-9a-f]{64}$';
 select count(*) into missing from public.player_saves s where not exists(select 1 from public.save_integrity_snapshots_v20170 x where x.user_id=s.user_id and x.revision=s.revision and x.save_sha256=s.integrity_sha256);
 select count(*) into revbad from (select user_id,revision,lag(revision) over(partition by user_id order by captured_at,revision) p from public.save_integrity_snapshots_v20170) q where p is not null and revision<p;
 select count(*) filter(where severity='critical'),count(*) filter(where severity='high'),count(*) filter(where severity='medium') into oc,oh,om from public.save_integrity_incidents_v20170 where resolved=false;
 ready:=coalesce(cfg.armed,false) and malformed=0 and missing=0 and revbad=0 and oc=0 and oh=0 and om<=coalesce(cfg.max_open_medium,0);
 insert into public.save_integrity_scan_runs_v20170(total_saves,malformed,missing_snapshot,revision_anomaly,open_critical,open_high,open_medium,ready,details,checked_by)
 values(total,malformed,missing,revbad,oc,oh,om,ready,jsonb_build_object('armed',cfg.armed,'maxOpenMedium',cfg.max_open_medium),left(coalesce(p_actor,''),200)) returning id into rid;
 return jsonb_build_object('version','20.17.0','ready',ready,'scanId',rid,'checkedAt',now(),'counts',jsonb_build_object('totalSaves',total,'malformed',malformed,'missingSnapshot',missing,'revisionAnomaly',revbad,'critical',oc,'high',oh,'medium',om),'armed',cfg.armed);
end$$;

create or replace function public.powder_save_integrity_posture_v20170()
returns jsonb language plpgsql security definer set search_path=public as $$
declare cfg public.save_integrity_config_v20170;last public.save_integrity_scan_runs_v20170;stale boolean:=true;ready boolean:=false;
begin
 select * into cfg from public.save_integrity_config_v20170 where id=1;
 select * into last from public.save_integrity_scan_runs_v20170 order by checked_at desc limit 1;
 stale:=last.id is null or last.checked_at<now()-make_interval(hours=>coalesce(cfg.max_snapshot_age_hours,24));
 ready:=coalesce(cfg.armed,false) and coalesce(last.ready,false) and not stale and last.open_critical=0 and last.open_high=0 and last.malformed=0 and last.missing_snapshot=0 and last.revision_anomaly=0;
 return jsonb_build_object('version','20.17.0','ready',ready,'armed',coalesce(cfg.armed,false),'checkedAt',now(),'scanStale',stale,'lastScan',case when last.id is null then null else to_jsonb(last) end,
 'guards',jsonb_build_object('serverHashEnvelope',true,'revisionRegressionBlocked',true,'powWipeBlocked',true,'schemaDowngradeBlocked',true,'criticalBranchLossBlocked',true,'snapshotHistory',true,'multiDeviceDiagnostics',true));
end$$;

create or replace function public.powder_save_integrity_arm_v20170(p_armed boolean,p_actor text)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
 update public.save_integrity_config_v20170 set armed=coalesce(p_armed,false),updated_at=now(),updated_by=left(coalesce(p_actor,''),200) where id=1;
 return public.powder_save_integrity_posture_v20170();
end$$;

create or replace function public.powder_save_integrity_resolve_v20170(p_id bigint,p_actor text,p_note text)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
 if length(btrim(coalesce(p_note,'')))<8 then raise exception 'SAVE20170_RESOLUTION_NOTE_REQUIRED';end if;
 update public.save_integrity_incidents_v20170 set resolved=true,resolved_at=now(),resolved_by=left(coalesce(p_actor,''),200),details=details||jsonb_build_object('resolutionNote',left(p_note,1200),'resolvedAt',now()) where id=p_id and resolved=false;
 if not found then raise exception 'SAVE20170_INCIDENT_NOT_FOUND';end if;
 return jsonb_build_object('ok',true,'id',p_id,'resolvedAt',now());
end$$;

