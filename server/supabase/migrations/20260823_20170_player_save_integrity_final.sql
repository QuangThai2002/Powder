select s.user_id,s.revision,coalesce((x.j->>'saveVersion')::int,0),coalesce(s.schema_version,0),coalesce(s.app_version,''),coalesce(s.device_id,''),x.j->>'saveSha256',x.j->>'mainSha256',x.j->>'worldSha256',x.j->>'powIdsSha256',x.j->>'lessonsSha256',coalesce((x.j->>'powCount')::int,0),coalesce((x.j->>'lessonsCount')::int,0),coalesce((x.j->>'equipmentCopies')::bigint,0),coalesce((x.j->>'artifactInstances')::int,0),coalesce((x.j->>'criticalShape')::boolean,false),x.j,now()
