-- Powder 20.5.0 · Player Support / GM Console
create table if not exists public.support_cases_v2050 (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null default 'general' check (category in ('account','save','reward','pvp','event','technical','report','general')),
  priority text not null default 'normal' check (priority in ('low','normal','high','critical')),
  subject text not null check (char_length(subject) between 3 and 160),
  description text not null default '',
  status text not null default 'open' check (status in ('open','investigating','waiting_player','waiting_admin','resolved','closed')),
  assigned_to text not null default '',
  created_by text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by text not null default ''
);
create index if not exists support_cases_v2050_user_idx on public.support_cases_v2050(user_id,updated_at desc);
create index if not exists support_cases_v2050_status_idx on public.support_cases_v2050(status,priority,updated_at desc);

create table if not exists public.support_case_notes_v2050 (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.support_cases_v2050(id) on delete cascade,
  author_email text not null default '',
  author_role text not null default 'support',
  note text not null check (char_length(note) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists support_case_notes_v2050_case_idx on public.support_case_notes_v2050(case_id,created_at desc);

create table if not exists public.support_compensation_requests_v2050 (
  id uuid primary key default gen_random_uuid(),
  case_id uuid references public.support_cases_v2050(id) on delete set null,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'Bồi thường hỗ trợ Powder',
  reason text not null default '',
  rewards jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending','approved','rejected','sent')),
  requested_by text not null default '',
  requested_at timestamptz not null default now(),
  reviewed_by text not null default '',
  reviewed_at timestamptz,
  review_note text not null default '',
  campaign_id uuid references public.mail_campaigns(id) on delete set null,
  batch_id uuid references public.compensation_batches(id) on delete set null
);
create index if not exists support_comp_req_user_idx on public.support_compensation_requests_v2050(user_id,requested_at desc);
create index if not exists support_comp_req_status_idx on public.support_compensation_requests_v2050(status,requested_at desc);

